import assert from 'node:assert/strict';
import { createServer } from 'vite';
import { chromium } from 'playwright-core';
import fs from 'node:fs/promises';
await fs.mkdir('tmp/timeline-multiselect', { recursive: true });
const server = await createServer({ server: { host: '127.0.0.1', port: 0 } }); await server.listen();
const browser = await chromium.launch({ channel: 'chrome', headless: true });
try {
    const page = await browser.newPage({ viewport: { width: 1600, height: 1000 } }), errors = [];
    page.on('pageerror', e => errors.push(e.message));
    await page.goto(`http://127.0.0.1:${server.httpServer.address().port}`); await page.waitForFunction(() => window.__director);
    const ids = await page.evaluate(() => {
        const api = window.__director, p = api.getProject(), actors = p.entities.filter(e => e.kind === 'actor').slice(0, 2), camera = p.entities.find(e => e.camera);
        p.entities = [camera, ...actors]; p.cuts = [{ time: 0, cameraId: camera.id }]; p.duration = 24; p.production = undefined;
        actors.forEach((e, i) => { e.path = null; e.clips = [{ id: `multi-${i}`, action: 'walk', speed: 1, start: 2 + i, end: 4 + i }, { id: `other-${i}`, action: 'idle', speed: 1, start: 10, end: 12 }]; });
        api.replaceProject(p); return actors.map(e => e.id);
    });
    await page.locator('#timeline-zoom').selectOption('1');
    const bar = i => page.locator(`[data-clip-id="multi-${i}"]`);
    const selection = () => page.evaluate(async () => (await window.__director.callTool('director_read', { sections: ['selection'] })).data.selection);
    const timings = () => page.evaluate(() => window.__director.getProject().entities.filter(e => e.kind === 'actor').map(e => e.clips.map(c => [c.start, c.end])));
    await bar(0).click({ modifiers: ['Control'] }); await bar(1).click({ modifiers: ['Control'] });
    assert.equal(await page.locator('.clip-selected').count(), 2); assert.equal((await selection()).clips.length, 2);
    await bar(1).click({ modifiers: ['Control'] }); assert.equal((await selection()).clips.length, 1);
    await bar(1).click({ modifiers: ['Control'] });
    const a = await bar(0).boundingBox();
    await page.mouse.move(a.x + 20, a.y + 12); await page.mouse.down();
    await page.mouse.move(a.x + 140, a.y + 12);
    assert.deepEqual(await timings(), [[[2, 4], [10, 12]], [[3, 5], [10, 12]]]);
    await page.mouse.up();assert.deepEqual(await timings(), [[[4, 6], [10, 12]], [[5, 7], [10, 12]]]); assert.equal(await page.locator('.clip-selected').count(), 2);
    assert.equal(await page.evaluate(() => !!document.documentElement.dataset.timelineDrag), false);
    await page.keyboard.press('Control+z'); assert.deepEqual(await timings(), [[[2, 4], [10, 12]], [[3, 5], [10, 12]]]);
    await bar(0).click({ modifiers: ['Control'] }); await bar(1).click({ modifiers: ['Control'] });
    const h = await bar(0).locator('[data-resize]').boundingBox();
    await page.mouse.move(h.x + h.width / 2, h.y + h.height / 2); await page.mouse.down(); await page.mouse.move(h.x + h.width / 2 + 60, h.y + h.height / 2); await page.mouse.up();
    assert.deepEqual(await timings(), [[[2, 5], [10, 12]], [[3, 6], [10, 12]]]);
    await page.locator('#timeline-to-ai').click();
    assert.match(await page.locator('#ai-scope-summary').textContent(), /2 个片段/);
    assert.equal(await page.locator('#ai-scope-toggle').getAttribute('aria-pressed'), 'true');
    assert.deepEqual((await selection()).entityIds.sort(), ids.sort());
    await page.screenshot({ path: 'tmp/timeline-multiselect/clips-ai.png' });
    await page.locator('#ai-close').click();
    await page.evaluate(() => window.__director.setTime(4));
    await page.keyboard.press('Control+b');
    assert.deepEqual((await timings()).map(a => a.length), [3, 3]);
    await page.locator('#timeline-content').focus(); await page.keyboard.press('Delete');
    assert.deepEqual((await timings()).map(a => a.length), [2, 2]);
    await page.keyboard.press('Control+z'); await page.keyboard.press('Control+z');
    assert.deepEqual(await timings(), [[[2, 5], [10, 12]], [[3, 6], [10, 12]]]);
    await bar(0).click({ modifiers: ['Control'] }); await bar(1).click({ modifiers: ['Control'] });
    const cancelBox = await bar(0).boundingBox();
    await page.mouse.move(cancelBox.x + 20, cancelBox.y + 12); await page.mouse.down(); await page.mouse.move(cancelBox.x + 80, cancelBox.y + 12);
    await page.keyboard.press('Escape'); await page.mouse.up();
    assert.deepEqual(await timings(), [[[2, 5], [10, 12]], [[3, 6], [10, 12]]]);
    assert.equal((await selection()).clips.length, 2);
    const ruler = await page.locator('.ruler').boundingBox();
    await page.keyboard.down('Control'); await page.mouse.move(ruler.x + 60, ruler.y + 9); await page.mouse.down(); await page.mouse.move(ruler.x + 360, ruler.y + 9); await page.mouse.up(); await page.keyboard.up('Control');
    const range = await selection(); assert.deepEqual(range.timeRange, { start: 1, end: 6 }); assert.equal(range.clips.length, 0); assert.deepEqual(range.entityIds, []);
    assert.equal(await page.locator('.timeline-selection-range').count(), 1);
    await page.locator('#timeline-to-ai').click(); assert.match(await page.locator('#ai-scope-summary').textContent(), /1.00–6.00 秒/);
    await page.screenshot({ path: 'tmp/timeline-multiselect/range-ai.png' });
    await page.locator('#ai-close').click();
    for (const id of ids) await page.locator(`#timeline-content [data-select="${id}"]`).first().click({ modifiers: ['Control'] });
    const objects = await selection(); assert.deepEqual(objects.entityIds.sort(), ids.sort()); assert.equal(objects.clips.length, 0);
    await page.setViewportSize({ width: 1280, height: 720 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    assert.equal(await page.locator('#timeline-to-ai').isVisible(), true);
    assert.deepEqual(errors, []);
    console.log('Ctrl selection/toggle, group move/resize, one-step undo, AI clip/time/object scopes, 1280px layout passed.');
} finally { await browser.close(); await server.close(); }
